def process_file_to_long(content, filename, tahun, indikator, mapping_kode):

    df = pd.read_csv(io.BytesIO(content))

    # --- KASUS KHUSUS 1: FILE KEMISKINAN (2 baris header) ---
    if 'Kabupaten/Kota' in df.columns and 'kode_kabupaten_kota' not in df.columns:
        df2 = pd.read_csv(io.BytesIO(content), skiprows=2, header=None)
        df2.columns = ['nama_kabupaten_kota', 'nilai']
        df2['tahun'] = tahun
        df2['nilai'] = pd.to_numeric(df2['nilai'], errors='coerce')

        # >>> TAMBAHAN BARU: buang baris yang nama kabupatennya kosong (NaN) <
        df2 = df2.dropna(subset=['nama_kabupaten_kota'])

        df2 = df2[~df2['nama_kabupaten_kota'].str.contains('Provinsi', case=False, na=False)]

        # >>> TAMBAHAN BARU: pastikan hasilnya persis 27 kabupaten/kota <
        assert len(df2) == 27, f"⚠️ {filename}: jumlah baris {len(df2)}, seharusnya 27."

        sub = df2[['nama_kabupaten_kota','tahun','nilai']].copy()
        sub['indikator'] = indikator
        return sub, mapping_kode

    # --- KASUS KHUSUS 2: FILE FASKES (long format) ---
    if 'jenis_faskes' in df.columns and 'jumlah_faskes' in df.columns:
        if 'tahun' not in df.columns:
            df['tahun'] = tahun
        agg = df.groupby(['kode_kabupaten_kota','tahun'], as_index=False)['jumlah_faskes'].sum()
        sub = agg[['kode_kabupaten_kota','tahun','jumlah_faskes']].rename(columns={'jumlah_faskes':'nilai'})
        sub['indikator'] = indikator
        return sub, mapping_kode

    # --- FILE STANDAR BPS/DINKES ---
    # Ambil mapping kode-nama jika ada
    if 'kode_kabupaten_kota' in df.columns and 'nama_kabupaten_kota' in df.columns:
        for _, row in df[['kode_kabupaten_kota','nama_kabupaten_kota']].drop_duplicates().iterrows():
            mapping_kode[row['nama_kabupaten_kota'].strip().upper()] = row['kode_kabupaten_kota']

    # Ambil kolom nilai
    if 'tahun' in df.columns:
        val_cols = [c for c in df.columns if c not in ['kode_kabupaten_kota','tahun','nama_kabupaten_kota','id','kode_provinsi','nama_provinsi','satuan']
                    and pd.api.types.is_numeric_dtype(df[c])]
        if val_cols:
            sub = df[['kode_kabupaten_kota','tahun',val_cols[0]]].rename(columns={val_cols[0]:'nilai'})
        else:
            year_cols = [c for c in df.columns if str(c).isdigit() and len(str(c))==4]
            if year_cols:
                sub = df.melt(id_vars=['kode_kabupaten_kota'], value_vars=year_cols,
                              var_name='tahun', value_name='nilai')
                sub['tahun'] = sub['tahun'].astype(int)
            else:
                return None, mapping_kode
    else:
        year_cols = [c for c in df.columns if str(c).isdigit() and len(str(c))==4]
        if year_cols:
            sub = df.melt(id_vars=['kode_kabupaten_kota'], value_vars=year_cols,
                          var_name='tahun', value_name='nilai')
            sub['tahun'] = sub['tahun'].astype(int)
        else:
            return None, mapping_kode

    sub['indikator'] = indikator
    return sub, mapping_kode

