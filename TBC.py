def get_importance_named(booster, feat_names, itype):
    raw = booster.get_score(importance_type=itype)
    named = {}
    for k, v in raw.items():
        idx = int(k[1:])
        if idx < len(feat_names):
            named[feat_names[idx]] = v
    return [named.get(f, 0.0) for f in feat_names]

