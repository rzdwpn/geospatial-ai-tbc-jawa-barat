def apply_threshold(proba, t0, t_high):
    preds = []
    for p in proba:
        if p[2] >= t_high:
            preds.append(2)
        elif p[0] >= t0:
            preds.append(0)
        else:
            preds.append(1)
    return np.array(preds)

